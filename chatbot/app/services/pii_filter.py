import re

"""사용자가 채팅으로 직접 입력한 텍스트에 개인정보로 보이는 패턴이 있으면 저장·AI 전달 전에
마스킹한다. AI(Gemini)가 계좌·개인정보를 먼저 언급하는 일은 없지만(자료에 없으면 모른다고
답하도록 시스템 프롬프트로 강제해뒀음), 사용자가 자유입력 질문에 실수로 자기 정보를 그대로
타이핑해서 넣으면 그 텍스트가 그대로 DB에 저장되고 Gemini API로도 넘어가는 문제가 있었다
(2026-08-09, 멘토 피드백 반영).

정규식 기반 패턴 매칭이라 100% 정확하진 않다 - 특히 계좌번호는 은행마다 자릿수·구분 방식이
달라 통일된 포맷이 없어서, "10~14자리 숫자"라는 느슨한 기준으로 추정 마스킹한다. 그래서 날짜·
금액처럼 숫자가 많이 붙는 다른 표현까지 과도하게 가릴 수 있다는 트레이드오프가 있다 - 개인정보
유출 쪽이 훨씬 치명적이라, 애매하면 가리는(false positive를 감수하는) 쪽으로 설계했다.
"""

# 경계 판단에 \b(단어 경계)를 쓰면 안 된다 - 파이썬 정규식은 유니코드 인식이라 한글도
# "단어 문자"로 취급돼서, "010-1234-5678로"처럼 번호 뒤에 조사가 공백 없이 바로 붙으면
# 숫자(단어 문자)->한글(역시 단어 문자)이라 경계로 인식되지 않아 매칭이 깨진다.
# 그래서 영문/숫자만 명시적으로 제외하는 lookaround로 경계를 판단한다.
_NOT_ALNUM_BEFORE = r"(?<![A-Za-z0-9])"
_NOT_ALNUM_AFTER = r"(?![A-Za-z0-9])"

# 주민등록번호: 앞 6자리(생년월일) - 뒷자리 첫 숫자(성별·세기 코드, 1~8만 유효)
_RRN = re.compile(_NOT_ALNUM_BEFORE + r"\d{6}[-\s]?[1-8]\d{6}" + _NOT_ALNUM_AFTER)

# 카드번호: 4-4-4-4 자리, 구분자(-,공백) 있거나 없거나
_CARD = re.compile(_NOT_ALNUM_BEFORE + r"\d{4}[-\s]?\d{4}[-\s]?\d{4}[-\s]?\d{4}" + _NOT_ALNUM_AFTER)

# 휴대폰번호: 010/011 등으로 시작
_PHONE = re.compile(_NOT_ALNUM_BEFORE + r"01[016789][-\s]?\d{3,4}[-\s]?\d{4}" + _NOT_ALNUM_AFTER)

# 유선전화(지역번호): 02(서울, 2자리) 또는 031~064(그 외 지역, 3자리)
_LANDLINE = re.compile(_NOT_ALNUM_BEFORE + r"0(2|[3-6]\d)[-\s]?\d{3,4}[-\s]?\d{4}" + _NOT_ALNUM_AFTER)

# 계좌번호(추정): 10~14자리 연속 숫자(중간에 구분자 - 허용). 은행마다 자릿수·구분이 달라
# 정확한 포맷이 없어서 느슨하게 잡는다 - 금액 표현("300000원", "30만원")처럼 뒤에 통화 단위가
# 바로 붙으면 계좌번호가 아닐 확률이 높아 그런 경우는 제외한다.
_ACCOUNT = re.compile(_NOT_ALNUM_BEFORE + r"\d[\d\-\s]{9,15}\d" + _NOT_ALNUM_AFTER + r"(?!\s*(원|만원|천원))")

# 아래 항목들은 카드번호·주민번호처럼 고정된 포맷이 없다(비밀번호는 임의 문자열이고,
# 여권번호·운전면허번호·부대코드·군번도 발급 시기·기관마다 자릿수가 달라 통일된 정규식이 없음).
# 그래서 "키워드 바로 뒤에 값처럼 보이는 게 붙어 있다" 형태로 느슨하게 잡는다 - 키워드만 있고
# 뒤에 실제 값이 없으면(예: "비밀번호를 잊어버렸어요") 매칭 안 되게 값 부분은 필수로 둔다.
# 키워드-값 사이에는 조사·콜론·공백 등이 최대 4글자까지 낄 수 있다고 보고 허용한다.
#
# 값 부분엔 숫자가 최소 1개 있어야 한다는 조건(전방탐색)을 넣었다(2026-08-12 발견 버그 수정) -
# 안 넣었을 땐 "카드 뒤 3자리(CVV)는 123이에요"처럼 키워드 표현 안에 알파벳(CVV)이 재등장하면
# 그 알파벳 자체를 "값"으로 착각해서 매칭이 거기서 끝나버리고, 정작 뒤에 있는 진짜 값(123)은
# 마스킹되지 않고 그대로 남았다(DB에서 실제로 확인됨).
_KEYWORD_CATEGORIES = [
    ("비밀번호/PIN/보안카드/OTP", r"(비밀번호|패스워드|비번|PIN|핀번호|보안카드번호|보안카드|OTP|일회용비밀번호|인증번호)"),
    ("카드 보안코드(CVV)", r"(CVV|씨브이브이|카드\s?보안코드|카드\s?뒤\s?(3|세)\s?자리)"),
    ("여권번호", r"(여권\s?번호)"),
    ("운전면허번호", r"(운전면허\s?번호|면허\s?번호)"),
    ("부대코드", r"(부대\s?코드)"),
    ("군번", r"(군번)"),
]
_KEYWORD_PATTERNS = [
    (label, re.compile(rf"{keyword}[^A-Za-z0-9]{{0,4}}(?=[A-Za-z0-9\-]*\d)[A-Za-z0-9\-]{{3,20}}"))
    for label, keyword in _KEYWORD_CATEGORIES
]


# 개인정보가 감지된 메시지는 AI 응답 생성을 아예 안 거치고 이 문구로 통일해서 답한다.
# 마스킹된 텍스트를 그대로 Gemini에 넘기면 "질문이 아니라 개인정보를 언급한 문장"인데도
# 의도 분류(info/counsel/irrelevant)가 LLM 판단이라 케이스마다 다르게 나왔다 - 주민등록번호는
# 안내형 답변, 계좌번호·비밀번호 등은 "무관련 질문" 범용 문구로 갈리는 등 일관성이 없었다
# (2026-08-12 발견). 개인정보 언급 자체는 항상 같은 안내로 답하도록 결정적으로 분기한다.
PII_DETECTED_REPLY = (
    "입력하신 내용에 개인정보로 보이는 정보가 있어 안전을 위해 따로 안내해 드리기 어렵지 말입니다. "
    "개인정보는 저장하지 않으니 앞으로는 입력하지 말아 주시기 바랍니다. "
    "다른 금융 상품이나 재무 상담에 대해 궁금한 점이 있으십니까?"
)


def mask_pii(text: str) -> str:
    """개인정보로 보이는 패턴을 찾아 마스킹한 텍스트를 반환한다. 원본은 절대 그대로 저장/전달하지 않는다."""
    if not text:
        return text
    masked = text
    # 키워드 기반 항목을 먼저 처리 - 뒤의 고정 포맷 패턴(주민번호 등)과 우연히 겹칠 때
    # 더 구체적인 맥락(키워드)이 있는 쪽을 우선 적용하기 위함.
    for label, pattern in _KEYWORD_PATTERNS:
        masked = pattern.sub(f"[{label} 마스킹됨]", masked)
    masked = _RRN.sub("[주민등록번호 마스킹됨]", masked)
    masked = _CARD.sub("[카드번호 마스킹됨]", masked)
    masked = _PHONE.sub("[전화번호 마스킹됨]", masked)
    masked = _LANDLINE.sub("[전화번호 마스킹됨]", masked)
    masked = _ACCOUNT.sub("[계좌번호로 추정되어 마스킹됨]", masked)
    return masked
